/**
 * Regression tests for a stranded GENERIC generated chain.
 *
 * A generic generated chain -- `performer: "any"` on every step, which is
 * what `convertAction` emits when it is handed `"any"` -- is repairable
 * through the ordinary generic-action rule, not a special case, even though:
 *
 *   - the ordinary generic-action conversion loop skips chain steps entirely
 *     (they are converted whole, never one at a time), and
 *   - the whole-chain loop skips anything whose steps are not performed by
 *     the changed role, which `"any"` never is.
 *
 * A capability change that strands a generic chain -- no role in the puzzle
 * can perform it any more -- must still find that repair, on a puzzle the
 * same operator library repairs by hand as soon as the chain's performer is
 * written as the role.
 *
 * A generic action is offered for conversion only when it is STRANDED --
 * when no role in the puzzle can perform it any more -- because otherwise
 * `"any"` is still the correct performer and rewriting it would narrow a
 * working action for no reason. `orphanedGenericChain` is that same test for
 * a chain, where "can perform it" means "can perform every link".
 *
 * The fixtures below are generated by the real `convertAction` rather than
 * hand-written -- so none of them depends on a shape only a test author knows
 * how to spell, and the input is provably a shape the generator actually
 * emits.
 */
import { test } from "node:test";
import assert from "node:assert/strict";

import { certify, isCertificate } from "../src/certify";
import { convertAction } from "../src/convert";
import { type Action, type Primitive, type Puzzle, type Role, type RoleId, emptyState } from "../src/model";
import { recompile } from "../src/recompile";
import { validatePuzzle } from "../src/validate";

const SCAN_TWO: Primitive = { id: "scan.two", capability: "scan", maxOptions: 2, splittable: true, label: "scan" };
const VOICE_TWO: Primitive = { id: "voice.two", capability: "voice", maxOptions: 2, splittable: true, label: "voice" };
/** A `voice` primitive that cannot present the 4-way choice in one step and cannot split: the honest "no conversion exists". */
const VOICE_ONE: Primitive = { id: "voice.one", capability: "voice", maxOptions: 1, splittable: false, label: "voice" };

/**
 * A real generated chain, derived from the generator itself rather than
 * hand-written: a
 * 4-option, answer-gated `gate` converted into a capability no single step can
 * present, so `convertAction` really does emit a two-step chain. `performer`
 * is the role the generator is asked to build the chain for, which is also the
 * performer on every step it emits -- `"any"` for the case below, a named
 * role for the label control, which is about the label and nothing else.
 */
function generatedChainPuzzle(options: {
  roles: Role[];
  primitives: Primitive[];
  performer?: RoleId;
  label?: string;
}): Puzzle {
  const performer = options.performer ?? "any";
  const base: Puzzle = { id: "stranded-generic-gate", roles: options.roles, primitives: options.primitives, goalFlags: ["goal"], actions: [] };
  const gate: Action = {
    id: "gate",
    performer,
    needs: "scan",
    requiresTokens: ["answer"],
    requiresFlags: [],
    producesTokens: [],
    setsFlags: ["goal"],
    options: 4,
    answerToken: "answer",
    label: options.label ?? "gate",
  };
  const converted = convertAction(base, gate, performer, "scan", SCAN_TWO);
  assert.ok(converted, "the fixture is a real generator output; convertAction must produce it");
  assert.equal(converted.actions.length, 2, "a 4-way choice under a 2-option primitive splits into exactly two steps");
  assert.equal(
    converted.actions.every((step) => step.performer === performer),
    true,
    "every step of a generated chain names the performer it was generated for",
  );
  return { ...base, actions: converted.actions };
}

/** The puzzle: one role C, holding `scan`, switching to `voice`, with a generic chain. */
function soleRolePuzzle(primitives: Primitive[] = [SCAN_TWO, VOICE_TWO]): Puzzle {
  return generatedChainPuzzle({ roles: [{ id: "C", capabilities: ["scan"], privateTokens: ["answer"] }], primitives });
}

/** The chain steps of a puzzle, in id order (validated chains are complete and consecutive from 1). */
function chainSteps(puzzle: Puzzle): Action[] {
  return puzzle.actions.filter((action) => action.id.startsWith("§"));
}

test("stranded-generic-1. round-trip-generic-chain: a stranded `any` chain has a repair and gets it, instead of a definitive no_valid_recompile", () => {
  const puzzle = soleRolePuzzle();
  const start = emptyState();

  // Preconditions: this is certified input, so `no_valid_recompile` for it is
  // a claim about the operator space, not about the puzzle being nonsense.
  assert.equal(validatePuzzle(puzzle).ok, true, "a real generator output must round-trip");
  const before = certify(puzzle, start);
  assert.equal(isCertificate(before) && before.ok, true, "the fixture must certify before the change");

  // A stranded `any` chain must recompile to `ok`, the same as the equivalent
  // chain with `performer: "C"` -- reporting `no_valid_recompile` after 1
  // operator ("no role has scan") would be wrong for a puzzle the same
  // operator library repairs by hand.
  const result = recompile(puzzle, start, "C", ["voice"]);
  assert.equal(result.kind, "ok", `expected a repair, got ${result.kind}: ${JSON.stringify(result)}`);
  if (result.kind !== "ok") return;

  // The repair is a conversion of the chain, not something that happened to
  // leave it alone -- the capability change on its own is a failed candidate
  // here, since C is the only role and it can no longer scan.
  assert.ok(
    result.diff.some((entry) => entry.op === "convert"),
    `expected the chain to be converted, got ${JSON.stringify(result.diff)}`,
  );
  assert.equal(result.diff[0]!.op, "capability_change", "every repair is the capability change plus operators on top of it");

  // Guard rail 1: the output is ordinary input. This is `validatePuzzle`'s
  // whole-chain round trip -- the same gate `validate.ts` builds and made
  // exact -- applied to what the repair actually produced.
  const validated = validatePuzzle(result.puzzle);
  assert.equal(
    validated.ok,
    true,
    `the repaired puzzle must round-trip: ${validated.ok ? "" : JSON.stringify(validated.errors)}`,
  );

  // Guard rail 2: the repaired chain is still uniform -- one performer, one
  // capability, the same breadth, ids consecutive from 1, one progress token
  // per link. `convertAction` emits exactly this and the round trip above
  // already enforces it field for field; asserted directly so a regression
  // says which invariant broke rather than only that some field differs.
  const steps = chainSteps(result.puzzle);
  assert.equal(steps.length, 2, "the 4-way choice still needs two 2-option voice steps");
  assert.equal(new Set(steps.map((step) => step.performer)).size, 1, "a chain is performed by exactly one performer");
  assert.equal(new Set(steps.map((step) => step.needs)).size, 1, "a chain needs exactly one capability");
  assert.deepEqual(
    steps.map((step) => step.id),
    ["§gate__step1", "§gate__step2"],
    "the chain keeps its generated ids, consecutive from 1",
  );
  assert.equal(steps.every((step) => step.needs === "voice"), true, "the chain was retargeted at the capability C now has");
  assert.deepEqual(
    steps.map((step) => step.producesTokens),
    [["§gate__progress1"], []],
    "each link still produces exactly the progress token the next link requires, and the last link still produces none",
  );

  // Guard rail 3: nobody was quietly demoted to decorative. `certify` proves
  // this per role inside the search, and the winner's own certificate is
  // returned -- asserted here so the repair is not merely "some puzzle that
  // validates".
  assert.equal(result.certificate.ok, true, "the winning candidate's certificate must be `ok`");
  const necessity = Object.values(result.certificate.necessity);
  assert.equal(necessity.length, result.puzzle.roles.length, "every role must have a necessity proof");
  assert.equal(necessity.every((proof) => proof.necessary), true, "no role may become unnecessary");
});

test("stranded-generic-2. a generic chain that genuinely cannot be repaired still gets the honest typed outcome, not a repair", () => {
  // C still has a capability and the puzzle still declares a primitive for it,
  // but that primitive cannot present a 4-way choice in one step and cannot
  // split into steps that could. No role has `scan` after the change, there is
  // no second role to reassign to and no other role's token to hand off, so
  // the operator space really is exhausted and the repair for a stranded
  // generic chain must not invent a candidate for it.
  const puzzle = soleRolePuzzle([SCAN_TWO, VOICE_ONE]);
  const start = emptyState();
  assert.equal(validatePuzzle(puzzle).ok, true, "the fixture is still legal input");

  const result = recompile(puzzle, start, "C", ["voice"]);
  assert.equal(result.kind, "no_valid_recompile", `expected an honest refusal, got ${JSON.stringify(result)}`);
  if (result.kind !== "no_valid_recompile") return;
  assert.equal(result.operatorsTried.length, 1, "only the capability change itself was a candidate; nothing else applied");
  assert.equal(result.operatorsTried[0]!.ok, false);
  assert.match(result.reason, /no role in the puzzle has it/, "the reason must still say why the chain is inaccessible");
});

test("stranded-generic-3. control: a generic chain a remaining role can still perform is left generic -- `any` is preserved where it is correct", () => {
  // Two roles: C loses `scan`, D keeps it. The chain is not stranded -- D can
  // still perform every link -- so the stranded-chain repair must not fire. The
  // repair here is the handoff that keeps C necessary, and the chain must come
  // back untouched, still performed by "any".
  const puzzle = generatedChainPuzzle({
    roles: [
      { id: "C", capabilities: ["scan"], privateTokens: [] },
      { id: "D", capabilities: ["scan"], privateTokens: ["answer"] },
    ],
    primitives: [SCAN_TWO, VOICE_TWO],
  });
  const start = emptyState();
  assert.equal(validatePuzzle(puzzle).ok, true, "the fixture is a real generator output");

  const result = recompile(puzzle, start, "C", ["voice"]);
  assert.equal(result.kind, "ok", `expected a repair, got ${JSON.stringify(result)}`);
  if (result.kind !== "ok") return;

  assert.equal(
    result.diff.some((entry) => entry.op === "convert"),
    false,
    `nothing needed converting: the chain is still performable by D, got ${JSON.stringify(result.diff)}`,
  );
  const steps = chainSteps(result.puzzle);
  assert.equal(steps.length, 2);
  assert.equal(steps.every((step) => step.performer === "any"), true, "the generic performer is preserved where it is still correct");
  assert.equal(steps.every((step) => step.needs === "scan"), true, "the chain still needs the capability it always needed");
});

test("stranded-generic-4. positive control: a source label that already ends in the generator's suffix round-trips, certifies, and recompiles", () => {
  // `recoverChainLabel` strips the ONE known suffix the generator appends. A
  // source label that literally ends in that text is still unambiguous,
  // because the suffix appended to it is the outer one: strip it and the
  // original string is back, verbatim. This case round-trips and recompiles
  // `ok` for real, kept here as the positive control it proves to be.
  const suffix = " (step 1 of 2, 2 options)";
  // Generated for C, not for "any": this control is about the label alone and
  // must not depend on stranded-generic-1, so a C-performer chain round-trips
  // and recompiles `ok` independently of it.
  const puzzle = generatedChainPuzzle({
    roles: [{ id: "C", capabilities: ["scan"], privateTokens: ["answer"] }],
    primitives: [SCAN_TWO, VOICE_TWO],
    performer: "C",
    label: `gate${suffix}`,
  });
  const start = emptyState();

  const steps = chainSteps(puzzle);
  assert.deepEqual(
    steps.map((step) => step.label),
    [`gate${suffix}${suffix}`, `gate${suffix} (step 2 of 2, 2 options)`],
    "the appended suffix is the outer one, so the label is doubled rather than ambiguous",
  );

  assert.equal(validatePuzzle(puzzle).ok, true, "a label ending in the generator's own suffix is not a forgery; the round trip must accept it");
  const certificate = certify(puzzle, start);
  assert.equal(isCertificate(certificate) && certificate.ok, true, "it must certify too");

  const result = recompile(puzzle, start, "C", ["voice"]);
  assert.equal(result.kind, "ok", `expected a repair, got ${JSON.stringify(result)}`);
  if (result.kind !== "ok") return;
  assert.equal(validatePuzzle(result.puzzle).ok, true, "and the repair's output must round-trip, labels included");
});
